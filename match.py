#Example using match-case statement

letter=input('Enter any character:')
match(letter):
    case 'a':
        print('Vowel')
    case 'e':
        print('Vowel')
    case 'i':
        print('Vowel')
    case 'o':
        print('Vowel')
    case 'u':
        print('Vowel')
    case _:
        print('Not a vowel')

    
